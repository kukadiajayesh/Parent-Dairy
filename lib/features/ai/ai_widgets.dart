/// "92%" / "Check" — how sure the model was about one row.
class ConfidencePill extends StatelessWidget {
  const ConfidencePill(this.confidence, {super.key, this.forceReview = false});

  final double confidence;
  final bool forceReview;

  @override
  Widget build(BuildContext context) {
    final k = context.t;
    final low = forceReview || confidence < 0.75;
    return StatusPill(
      label: low ? 'Check' : '${(confidence * 100).round()}%',
      background: low ? k.warnC : k.surf2,
      foreground: low ? k.warnInk : k.tx3,
      dotColor: low ? k.warn : null,
    );
  }
}

