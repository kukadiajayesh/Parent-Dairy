/// The consent gate every AI action passes through (prompt 02 §G.1).
///
/// Returns true when the caller may proceed: the layer is on, the parent
/// has accepted the current consent version, at least one key exists, and
/// the phone is online. Each miss is explained rather than swallowed.
Future<bool> ensureAiReady(BuildContext context) async {
  final state = AppScope.read(context);
  if (!state.aiAvailable) return false;

  final root = Navigator.of(context, rootNavigator: true);
  if (!state.aiConsented) {
    final accepted = await root.pushNamed<bool>(Routes.aiConsent) ?? false;
    if (!accepted || !context.mounted) return false;
  }

  if (!state.aiKeys.isLoaded) await state.aiKeys.load();
  if (!context.mounted) return false;

  if (state.aiKeys.keys.isEmpty) {
    AppToast.show(
      context,
      title: 'Add a Gemini key first',
      description: 'Paste a free Google AI Studio key in More → AI.',
      kind: ToastKind.warn,
      actionLabel: 'Open',
      onAction: () => root.pushNamed(Routes.aiSettings),
    );
    return false;
  }

  if (state.isOffline) {
    AppToast.failure(
      context,
      const AppFailure(
        FailureKind.offline,
        'Generating needs an internet connection.',
      ),
      title: "You're offline",
    );
    return false;
  }
  return true;
}

