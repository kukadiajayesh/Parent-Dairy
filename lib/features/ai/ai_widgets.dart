/// The failure state every AI screen shows: the parent-readable message,
/// Try again when retrying could help, and a way out.
class AiFailureView extends StatelessWidget {
  const AiFailureView({
    super.key,
    required this.failure,
    required this.onRetry,
    required this.onCancel,
    this.title = "Gemini couldn't do that",
  });

  final AppFailure failure;
  final VoidCallback onRetry;
  final VoidCallback onCancel;
  final String title;

  @override
  Widget build(BuildContext context) => ErrorStateView(
    title: title,
    description: failure.message,
    actionLabel: failure.canRetry ? 'Try again' : 'Change settings',
    onAction: failure.canRetry
        ? onRetry
        : () => Navigator.of(context, rootNavigator: true).pushNamed(Routes.aiSettings),
    onCancel: onCancel,
  );
}

/// A count stepper row for the question mix.
class CountStepper extends StatelessWidget {
  const CountStepper({
    super.key,
    required this.label,
    required this.value,
    required this.onChanged,
    this.max = 40,
  });

  final String label;
  final int value;
  final ValueChanged<int> onChanged;
  final int max;

  @override
  Widget build(BuildContext context) {
    final k = context.t;
    return Row(
      children: [
        Expanded(
          child: Text(
            label,
            style: TextStyle(
              fontSize: 14,
              fontWeight: FontWeight.w600,
              color: value == 0 ? k.tx4 : k.tx,
            ),
          ),
        ),
        AppIconButton(
          size: 34,
          borderRadius: 10,
          background: k.surf2,
          onTap: value == 0 ? null : () => onChanged(value - 1),
          child: Text('−', style: TextStyle(fontSize: 18, color: k.tx2)),
        ),
        SizedBox(
          width: 36,
          child: Text(
            '$value',
            textAlign: TextAlign.center,
            style: const TextStyle(fontSize: 15, fontWeight: FontWeight.w800),
          ),
        ),
        AppIconButton(
          size: 34,
          borderRadius: 10,
          background: k.priC,
          hoverBackground: k.priCH,
          onTap: value >= max ? null : () => onChanged(value + 1),
          child: StrokeIcon(AppIcons.plus, size: 16, color: k.priInk),
        ),
      ],
    );
  }
}
